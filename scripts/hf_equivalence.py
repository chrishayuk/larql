"""Numerical equivalence of a VINDEX3 container against Hugging Face transformers.

usage:
  python3 -I scripts/hf_equivalence.py --repo google/gemma-3-270m-it \
      --revision <sha> --container <dir>.vindex3 --larql <binary> \
      --name gemma-3-270m-it --out-dir <dir> [--hf-dtype f32]

Feeds BOTH sides the exact same token ids (no attention mask, no padding)
and compares logits, never text. Arms:

  reference/cached    `vindex3 exec --backend reference --logit-dump`
  reference/prefill   `vindex3 exec --backend reference --prefill-logit-dump`
  production/cached   the same with `--backend production`
  production/prefill

each against one transformers forward over the same ids (`use_cache=False`,
eager attention). Cases: the chat-templated question, a raw prompt, lengths
around the sliding window (short, W-1, W, W+1, 2W+), and a greedy decode
generated by LARQL production that crosses the window boundary — checked
at every decode step against transformers AND against a fresh LARQL prefill
of the same prefix, so a cached path and a prefill path that are both wrong
cannot agree and pass. transformers' own cache is spot-checked against its
no-cache forward over the decode.

Writes `<name>.equivalence.json` (appended per run, see
`equivalence_metrics.append_run`) and `<name>.equivalence.md` into
`--out-dir`. The method and its gates live in `equivalence_metrics.py`.
"""

