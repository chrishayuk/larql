DTYPES = {"f32": torch.float32, "bf16": torch.bfloat16}
#: arm name → (`--backend`, extra exec flags, tolerance family). `production`
#: is the default serving arm (`--representation-source auto`: BF16
#: operands may be requantised to Q8 at load — lossy by declaration);
#: `production-stored` forbids manufacturing any representation, so the
#: production kernels run on the stored BF16 bytes.
ARMS = {
    "reference": ("reference", [], "reference"),
    "production": ("production", [], "production"),
    "production-stored": ("production", ["--representation-source", "stored"], "production"),
}
SHORT_LENGTH = 8
#: The long case reaches past twice the window by this many tokens.
LONG_OVERHANG = 16
DEFAULT_DECODE_STEPS = 40
DEFAULT_QUESTION = "What is the capital of France? Answer in one sentence."
DEFAULT_RAW_PROMPT = "The capital of France is"
EXPECTED_ANSWER = "Paris"
TOKENIZER_FILES = ("tokenizer.json", "tokenizer_config.json", "chat_template.jinja")
#: A natural-language passage, repeated to build long valid sequences.
PASSAGE = (
    "The river rises in the hills to the north and runs south through farmland, "
    "past three market towns and a cathedral city, before it widens into a broad "
    "estuary where the tide comes in twice a day. In the spring the water is high "
    "and brown with soil from the fields; by late summer it runs clear and slow, "
    "and children swim from the shingle banks below the old stone bridge. "
)
LOGIT_CHUNK = 64
#: How a composite (multimodal) checkpoint's text weights are renamed onto
#: a causal-LM text model.
COMPOSITE_TEXT_KEY_MAPPING = {
    r"^language_model\.model\.": "model.",
    r"^language_model\.lm_head\.": "lm_head.",
    r"^model\.language_model\.": "model.",
}


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def run(cmd: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True)


# ── identity ───────────────────────────────────────────────────────────


def tokenizer_digests(repo: str, revision: str) -> dict:
    out = {}
    for name in TOKENIZER_FILES:
        try:
            out[name] = sha256_file(Path(hf_hub_download(repo, name, revision=revision)))
        except Exception:  # noqa: BLE001 — absent file is recorded as absent
            out[name] = None
    return out


def container_identity(container: Path) -> dict:
    index = json.loads((container / "index.json").read_text())
    payloads = {
        name: {key: rep.get(key) for key in ("encoding", "payload_sha256", "segment_sha256")}
        for name, rep in index.get("representations", {}).items()
    }
    return {
        "path": str(container),
        "index_json_sha256": sha256_file(container / "index.json"),
        "representations": payloads,
    }


def larql_commit(larql: Path) -> dict:
    repo = larql.resolve().parents[2]
    head = run(["git", "-C", str(repo), "rev-parse", "HEAD"]).stdout.strip()
    dirty = bool(run(["git", "-C", str(repo), "status", "--porcelain", "--untracked-files=no"]).stdout.strip())
    return {"commit": head, "dirty": dirty, "binary_sha256": sha256_file(larql)}


def hardware() -> dict:
    chip = run(["sysctl", "-n", "machdep.cpu.brand_string"]).stdout.strip()
    memory = run(["sysctl", "-n", "hw.memsize"]).stdout.strip()
    return {"chip": chip, "memory_bytes": int(memory or 0), "os": platform.platform()}


# ── cases ──────────────────────────────────────────────────────────────


def passage_ids(tokenizer, length: int) -> list[int]:
    """BOS + the passage repeated, cut to exactly `length` ids."""
    body = tokenizer(PASSAGE, add_special_tokens=False)["input_ids"]
    ids = [tokenizer.bos_token_id]
    while len(ids) < length:
        ids.extend(body)
    return ids[:length]


def build_cases(tokenizer, window: int, question: str, raw_prompt: str) -> list[dict]:
    chat = tokenizer.apply_chat_template(
        [{"role": "user", "content": question}], add_generation_prompt=True
    )
    if not isinstance(chat, list):
        chat = chat["input_ids"]
    raw = tokenizer(raw_prompt)["input_ids"]
    cases = [
        {"name": "chat", "text": question, "ids": list(chat)},
        {"name": "raw", "text": raw_prompt, "ids": list(raw)},
    ]
    for name, length in (
        ("short", SHORT_LENGTH),
        ("window_minus_1", window - 1),
        ("window", window),
        ("window_plus_1", window + 1),
        ("two_windows_plus", 2 * window + LONG_OVERHANG),
    ):
        cases.append({"name": name, "text": "passage", "ids": passage_ids(tokenizer, length)})
    for case in cases:
        case["bos_present"] = bool(case["ids"]) and case["ids"][0] == tokenizer.bos_token_id
        case["length"] = len(case["ids"])
    return cases


# ── the two sides ──────────────────────────────────────────────────────


class Transformers:
    def __init__(self, repo: str, revision: str, dtype_name: str):
        config = AutoConfig.from_pretrained(repo, revision=revision)
        kwargs = {}
        # A composite checkpoint is loaded as its text model alone, through
        # its text config (transformers ignores `dtype` on the composite
        # wrapper and would load BF16).
        if getattr(config, "text_config", None) is not None:
            kwargs = {"config": config.text_config, "key_mapping": COMPOSITE_TEXT_KEY_MAPPING}
        model, info = AutoModelForCausalLM.from_pretrained(
            repo, revision=revision, dtype=DTYPES[dtype_name], attn_implementation="eager",
            output_loading_info=True, **kwargs
        )
        if info.get("missing_keys"):
            raise SystemExit(f"missing weights: {sorted(info['missing_keys'])[:10]}")
        self.model = model.to(DTYPES[dtype_name]).eval()
        self.dtype = dtype_name

    @torch.no_grad()
    def logits(self, ids: list[int]) -> np.ndarray:
        out = self.model(torch.tensor([ids]), use_cache=False)
        return out.logits[0].float().numpy()

    @torch.no_grad()
    def noise_floor(self, ids: list[int], eager_rows: np.ndarray) -> float:
        """transformers against itself: sdpa vs eager attention, max |Δ
        logprob| over every position — the scale at which f32 summation
        order alone moves the answer."""
        self.model.set_attn_implementation("sdpa")
        try:
            sdpa = self.model(torch.tensor([ids]), use_cache=False).logits[0].float().numpy()
        finally:
            self.model.set_attn_implementation("eager")
        return float(m.max_abs_logprob(sdpa, eager_rows).max())

    @torch.no_grad()
    def cached_logits(self, prompt: list[int], continuation: list[int]) -> np.ndarray:
        """Prompt prefill, then one cached step per continuation token: the
        rows predicting continuation[0..] (the last step's is dropped)."""
        out = self.model(torch.tensor([prompt]), use_cache=True)
        rows = [out.logits[0, -1].float().numpy()]
        past = out.past_key_values
        for token in continuation[:-1]:
            out = self.model(torch.tensor([[token]]), past_key_values=past, use_cache=True)
            past = out.past_key_values
            rows.append(out.logits[0, -1].float().numpy())
        return np.stack(rows)


class Larql:
    def __init__(self, binary: Path, container: Path, work: Path):
        self.binary, self.container, self.work = binary, container, work

    def _exec(self, arm: str, ids: list[int], extra: list[str]) -> str:
        backend, flags, _ = ARMS[arm]
        cmd = [str(self.binary), "vindex3", "exec", str(self.container), "--backend", backend,
               *flags, "--tokens", ",".join(map(str, ids)), *extra]
        done = run(cmd)
        if done.returncode != 0:
            raise RuntimeError(f"{' '.join(cmd[:6])} failed:\n{done.stderr[-2000:]}")
        return done.stdout

    def cached(self, arm: str, ids: list[int], tag: str) -> np.ndarray:
        out = self.work / f"{tag}-{arm}-cached.f32"
        self._exec(arm, ids, ["--logit-dump", str(out)])
        return np.fromfile(out, dtype="<f4").reshape(len(ids), -1)

    def prefill(self, arm: str, ids: list[int], lengths: list[int], tag: str) -> np.ndarray:
        out = self.work / f"{tag}-{arm}-prefill.f32"
        self._exec(arm, ids, ["--prefill-logit-dump", str(out),
                              "--prefill-lengths", ",".join(map(str, lengths))])
        return np.fromfile(out, dtype="<f4").reshape(len(lengths), -1)

    def generate(self, ids: list[int], steps: int) -> list[int]:
        stdout = self._exec("production", ids, ["--generate", str(steps)])
        line = next(l for l in stdout.splitlines() if l.startswith("generated ids:"))
        return [int(t) for t in line.split(":", 1)[1].replace(",", " ").split()]


# ── comparison ─────────────────────────────────────────────────────────


def arms_for(length: int, reference_limit: int | None) -> list[str]:
    """The arms a sequence of `length` runs on: the f32 reference
    interpreter is skipped above `reference_limit` (recorded, never
    silently), every production arm always runs."""
    return [arm for arm in ARMS
            if not (ARMS[arm][2] == "reference" and reference_limit is not None and length > reference_limit)]


def compare(arm: str, arm_rows: np.ndarray, hf_rows: np.ndarray, positions: list[int],
            record_top_at: set[int]) -> dict:
    """Arm rows vs transformers rows at the same positions."""
    if arm_rows.shape[1] != hf_rows.shape[1]:
        raise ValueError(f"vocabulary width differs: larql {arm_rows.shape[1]} vs hf {hf_rows.shape[1]}")
    max_abs, mass_bearing, verdicts, detail, top1_mismatch = [], [], [], {}, []
    for start in range(0, len(positions), LOGIT_CHUNK):
        a = m.log_softmax64(arm_rows[start:start + LOGIT_CHUNK])
        h = m.log_softmax64(hf_rows[start:start + LOGIT_CHUNK])
        max_abs.extend(np.abs(a - h).max(axis=-1).tolist())
        for offset in range(a.shape[0]):
            position = positions[start + offset]
            verdict, diffs = m.order_verdict(h[offset], a[offset], m.TIE_TOLERANCE[ARMS[arm][2]])
            verdicts.append(verdict)
            mass_bearing.append(m.max_abs_logprob_mass_bearing(h[offset], a[offset]))
            if int(np.argmax(a[offset])) != int(np.argmax(h[offset])):
                top1_mismatch.append(position)
            if verdict != m.PASS or position in record_top_at:
                detail[str(position)] = {
                    "verdict": verdict,
                    "diffs": diffs,
                    "hf_top6": m.top_k(h[offset]),
                    "larql_top6": m.top_k(a[offset]),
                }
    return {
        "positions": positions,
        "max_abs_logprob": max_abs,
        "max_abs_logprob_overall": max(max_abs),
        "max_abs_logprob_mass_bearing": mass_bearing,
        "max_abs_logprob_mass_bearing_overall": max(mass_bearing),
        "top5_verdict": m.worst(verdicts),
        "top1_mismatch_positions": top1_mismatch,
        "verdict_counts": {v: verdicts.count(v) for v in (m.PASS, m.TIE_SWAP, m.FAIL)},
        "recorded_positions": detail,
    }


def arm_gate(arm: str, result: dict) -> str:
    if result["top5_verdict"] == m.FAIL:
        return m.FAIL
    if ARMS[arm][2] == "reference" and result["max_abs_logprob_overall"] > m.REFERENCE_MAX_ABS_LOGPROB:
        return m.FAIL
    return result["top5_verdict"]


def evaluate_cases(hf: Transformers, larql: Larql, cases: list[dict],
                   reference_limit: int | None) -> list[dict]:
    for case in cases:
        ids, n = case["ids"], case["length"]
        hf_rows = hf.logits(ids)
        case["hf_noise_floor_sdpa_vs_eager"] = hf.noise_floor(ids, hf_rows)
        case["arms"] = {}
        for arm in arms_for(n, reference_limit):
            cached = compare(arm, larql.cached(arm, ids, case["name"]), hf_rows,
                             list(range(n)), {n - 1})
            prefill = compare(arm, larql.prefill(arm, ids, [n], case["name"]),
                              hf_rows[n - 1:n], [n - 1], {n - 1})
            case["arms"][arm] = {"cached": cached, "prefill": prefill,
                                 "gate": m.worst([arm_gate(arm, cached), arm_gate(arm, prefill)])}
        print(f"  {case['name']:>18} n={n:<5}" + "".join(
            f"  {arm}: cached {case['arms'][arm]['cached']['max_abs_logprob_overall']:.2e}"
            f" prefill {case['arms'][arm]['prefill']['max_abs_logprob_overall']:.2e}"
            f" [{case['arms'][arm]['gate']}]" for arm in case["arms"]), flush=True)
    return cases


def evaluate_decode(hf: Transformers, larql: Larql, tokenizer, window: int, steps: int,
                    reference_limit: int | None) -> dict:
    prompt = passage_ids(tokenizer, window - steps // 2)
    generated = larql.generate(prompt, steps)
    sequence = prompt + generated
    p = len(prompt)
    positions = list(range(p - 1, p - 1 + len(generated)))  # rows predicting generated[i]
    hf_rows = hf.logits(sequence)[positions]
    hf_cached = hf.cached_logits(prompt, generated)
    out = {
        "prompt_length": p, "window": window, "steps": len(generated),
        "crosses_window": p < window < p + len(generated),
        "prompt_ids": prompt, "generated_ids": generated, "generated_by": "production (--representation-source auto), greedy, cached decode",
        "hf_greedy_agrees": [int(np.argmax(hf_rows[i])) == g for i, g in enumerate(generated)],
        "hf_cache_vs_nocache_max_abs_logprob": float(m.max_abs_logprob(hf_cached, hf_rows).max()),
        "arms": {},
    }
    lengths = [q + 1 for q in positions]
    for arm in arms_for(len(sequence), reference_limit):
        cached_rows = larql.cached(arm, sequence, "decode")[positions]
        prefill_rows = larql.prefill(arm, sequence, lengths, "decode")
        record = set(positions)
        cached = compare(arm, cached_rows, hf_rows, positions, record)
        prefill = compare(arm, prefill_rows, hf_rows, positions, record)
        out["arms"][arm] = {
            "cached_vs_hf": cached, "prefill_vs_hf": prefill,
            "cached_vs_prefill_max_abs_logprob": float(m.max_abs_logprob(cached_rows, prefill_rows).max()),
            "gate": m.worst([arm_gate(arm, cached), arm_gate(arm, prefill)]),
        }
        print(f"  decode {arm}: cached {cached['max_abs_logprob_overall']:.2e} "
              f"prefill {prefill['max_abs_logprob_overall']:.2e} [{out['arms'][arm]['gate']}]", flush=True)
    return out


# ── ladder stages ──────────────────────────────────────────────────────


def admissible_stage(larql: Path, repo: str, revision: str) -> dict:
    done = run([str(larql), "vindex3", "plan", f"hf://{repo}@{revision}", "--capability", "text-generation"])
    try:
        summary = json.loads(done.stdout)["summary"]
    except (json.JSONDecodeError, KeyError):
        summary = None
    ok = done.returncode == 0 and summary is not None and summary["blocking"] == 0
    return m.stage("PASS" if ok else "FAIL", {"exit": done.returncode, "summary": summary})


def encoded_stage(larql: Path, container: Path) -> dict:
    done = run([str(larql), "vindex3", "inspect", str(container)])
    last = done.stdout.strip().splitlines()[-1] if done.stdout.strip() else ""
    return m.stage("PASS" if done.returncode == 0 and last == "container coherent" else "FAIL",
                   {"exit": done.returncode, "verdict": last})


def operational_stage(larql: Path, container: Path, question: str) -> dict:
    done = run([str(larql), "run", str(container), question, "-n", "40"])
    answer = done.stdout.strip()
    ok = done.returncode == 0 and EXPECTED_ANSWER in answer
    return m.stage("PASS" if ok else "FAIL", {"prompt": question, "answer": answer,
                                              "criterion": f"contains {EXPECTED_ANSWER!r}"})


def _runs(cases: list[dict], decode: dict, arm: str, case_keys=("cached", "prefill"),
          decode_keys=("cached_vs_hf", "prefill_vs_hf")) -> list[dict]:
    """Every comparison result an arm produced (skipped cases contribute none)."""
    out = [c["arms"][arm][k] for c in cases if arm in c["arms"] for k in case_keys]
    if arm in decode["arms"]:
        out += [decode["arms"][arm][k] for k in decode_keys]
    return out


def _gates(cases: list[dict], decode: dict, arm: str) -> list[str]:
    gates = [c["arms"][arm]["gate"] for c in cases if arm in c["arms"]]
    return gates + ([decode["arms"][arm]["gate"]] if arm in decode["arms"] else [])


def equivalent_stage(cases: list[dict], decode: dict) -> dict:
    """FAIL on any failed gate; PENDING when the worst is a tie swap (it
    needs adjudication, and is not a pass) or an arm skipped a case; PASS
    only when every arm ran every case and passed."""
    per_arm = {arm: m.worst(_gates(cases, decode, arm)) for arm in ARMS}
    skipped = {arm: [c["name"] for c in cases if arm not in c["arms"]]
               + (["decode"] if arm not in decode["arms"] else []) for arm in ARMS}
    verdict = m.worst(per_arm.values())
    if verdict == m.FAIL:
        status = "FAIL"
    elif verdict == m.TIE_SWAP or any(skipped.values()):
        status = "PENDING"
    else:
        status = "PASS"
    return m.stage(status, {
        "verdict": verdict,
        "gate_per_arm": per_arm,
        "skipped_per_arm": skipped,
        "max_abs_logprob_per_arm": {
            arm: max((r["max_abs_logprob_overall"] for r in _runs(cases, decode, arm)), default=None)
            for arm in ARMS},
        "max_abs_logprob_mass_bearing_per_arm": {
            arm: max((r["max_abs_logprob_mass_bearing_overall"] for r in _runs(cases, decode, arm)), default=None)
            for arm in ARMS},
        "top1_mismatches_per_arm": {
            arm: sum(len(r["top1_mismatch_positions"]) for r in _runs(cases, decode, arm)) for arm in ARMS},
        "hf_noise_floor_sdpa_vs_eager": max(c["hf_noise_floor_sdpa_vs_eager"] for c in cases),
        "cache_steps": decode["steps"],
        "decode_crosses_window": decode["crosses_window"],
    })


# ── report ─────────────────────────────────────────────────────────────


def markdown(name: str, run_record: dict) -> str:
    lines = [f"# {name} — HF equivalence (harness {m.HARNESS_VERSION})", "",
             f"- checkpoint: `{run_record['identity']['repo']}@{run_record['identity']['revision']}`",
             f"- LARQL: `{run_record['larql']['commit']}` (dirty: {run_record['larql']['dirty']})",
             f"- transformers {run_record['environment']['transformers']}, torch "
             f"{run_record['environment']['torch']}, HF dtype {run_record['arms_dtype']['transformers']}",
             f"- hardware: {run_record['environment']['hardware']['chip']}, "
             f"{run_record['environment']['hardware']['os']}", "",
             "| stage | status |", "|---|---|"]
    lines += [f"| {k} | {v['status']} |" for k, v in run_record["ladder"].items()]
    lines += ["", "max |Δ logprob| vs transformers (cached / prefill) and gate, per arm:", "",
              "| case | n | BOS | " + " | ".join(ARMS) + " |", "|---|---|---|" + "---|" * len(ARMS)]
    for c in run_record["cases"]:
        cells = [f"{c['arms'][a]['cached']['max_abs_logprob_overall']:.2e} / "
                 f"{c['arms'][a]['prefill']['max_abs_logprob_overall']:.2e} {c['arms'][a]['gate']}"
                 if a in c["arms"] else "skipped" for a in ARMS]
        lines.append(f"| {c['name']} | {c['length']} | {c['bos_present']} | " + " | ".join(cells) + " |")
    d = run_record["decode"]
    lines += ["", f"Decode: prompt {d['prompt_length']} + {d['steps']} greedy steps (window {d['window']}, "
              f"crosses: {d['crosses_window']}); HF greedy agrees on {sum(d['hf_greedy_agrees'])}/{d['steps']}; "
              f"HF cache vs no-cache max |Δ| {d['hf_cache_vs_nocache_max_abs_logprob']:.2e}."]
    for arm in d["arms"]:
        a = d["arms"][arm]
        lines.append(f"- {arm}: cached vs HF {a['cached_vs_hf']['max_abs_logprob_overall']:.2e}, prefill vs HF "
                     f"{a['prefill_vs_hf']['max_abs_logprob_overall']:.2e}, cached vs prefill "
                     f"{a['cached_vs_prefill_max_abs_logprob']:.2e} — {a['gate']}")
    lines += ["", f"Gates: reference max |Δ logprob| ≤ {m.REFERENCE_MAX_ABS_LOGPROB}; ordered top-{m.GATED_TOP_K} "
              f"vs transformers with tie tolerance {m.TIE_TOLERANCE} (tie swaps reported, not passed)."]
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", required=True)
    ap.add_argument("--revision", required=True)
    ap.add_argument("--container", required=True, type=Path)
    ap.add_argument("--larql", required=True, type=Path)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out-dir", required=True, type=Path)
    ap.add_argument("--hf-dtype", default="f32", choices=sorted(DTYPES))
    ap.add_argument("--decode-steps", type=int, default=DEFAULT_DECODE_STEPS)
    ap.add_argument("--question", default=DEFAULT_QUESTION)
    ap.add_argument("--raw-prompt", default=DEFAULT_RAW_PROMPT)
    ap.add_argument("--reference-max-length", type=int, default=None,
                    help="skip the f32 reference arm on sequences longer than this "
                         "(recorded; the equivalent stage then reads PENDING, never PASS)")
    args = ap.parse_args()

    identity = {"repo": args.repo, "revision": args.revision}
    tokenizer = AutoTokenizer.from_pretrained(args.repo, revision=args.revision)
    config = AutoConfig.from_pretrained(args.repo, revision=args.revision)
    window = int(getattr(getattr(config, "text_config", None) or config, "sliding_window"))
    # Identity first: a run that cannot name what it measured is not run.
    fixed = {"tokenizer_sha256": tokenizer_digests(args.repo, args.revision),
             "container": container_identity(args.container),
             "larql": larql_commit(args.larql)}
    hf = Transformers(args.repo, args.revision, args.hf_dtype)
    started = datetime.now(timezone.utc).isoformat()
    with tempfile.TemporaryDirectory() as work:
        larql = Larql(args.larql, args.container, Path(work))
