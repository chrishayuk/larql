fn synth_q6k_block(seed: u32) -> Vec<u8> {
    let mut block = vec![0u8; 210];
    // Deterministic pseudo-random bytes for ql (128), qh (64), scales (16).
    let mut s = seed;
    for b in &mut block[..208] {
        s = s.wrapping_mul(1664525).wrapping_add(1013904223);
        *b = (s >> 16) as u8;
    }
    // f16 d = 0.0625
    block[208] = 0x00;
    block[209] = 0x2C;
    block
}

