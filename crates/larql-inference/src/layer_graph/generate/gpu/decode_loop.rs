    /// A backend that fails a step part-way stops the loop with an error,
    /// and keeps the tokens produced before it. The loop used to stop and
    /// return those tokens as a complete, successful generation.
    #[test]
    fn a_failed_decode_step_is_an_error_with_the_tokens_before_it() {
        use crate::layer_graph::generate::detok::Detokenizer;
        use crate::layer_graph::generate::eos::EosConfig;
        use crate::layer_graph::generate::policy::GenerationRuntimeConfig;
        use crate::layer_graph::generate::sampling::{Sampler, SamplingConfig};

        /// Decode steps the backend completes before it fails.
        const GOOD_STEPS: usize = 2;
        const MAX_TOKENS: usize = 6;

        let run = |backend: MockGpuBackend| {
            let weights = make_test_q4k_weights();
            let index = make_test_q4k_vindex(&weights);
            let tokenizer = crate::test_utils::make_test_tokenizer(weights.vocab_size);
            let mut sampler = Sampler::new(SamplingConfig::greedy());
            let runtime = GenerationRuntimeConfig::default();
            let mut detok = Detokenizer::new(&tokenizer);
            let mut generated_ids: Vec<u32> = vec![0];
            run_decode_loop(
                &weights,
                &tokenizer,
                &index,
                &backend,
                &[],
                weights.hidden_size,
                weights.intermediate_size,
                weights.arch.norm_weight_offset(),
                5,
                &runtime,
                &mut sampler,
                &mut detok,
                &EosConfig::empty(),
                &mut generated_ids,
                /*current_token_id=*/ 0,
                MAX_TOKENS,
                None,
                &mut |_id, _text, _prob| {},
            )
        };

        // The control: a backend that never fails runs to max_tokens with
        // no error, so the error below is the failure and nothing else.
        let whole = run(MockGpuBackend::new());
        assert!(whole.error.is_none(), "{:?}", whole.error);
        assert_eq!(whole.tokens.len(), MAX_TOKENS - 1);

        let cut_short = run(MockGpuBackend::failing_after(GOOD_STEPS));
        assert_eq!(cut_short.tokens.len(), GOOD_STEPS);
        let error = cut_short.error.expect("a failed step must be reported");
        assert!(error.to_string().contains("decode step"), "{error}");
    }

