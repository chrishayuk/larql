def is_sha(v) -> bool:
    return isinstance(v, str) and len(v) == SHA_HEX and all(c in "0123456789abcdef" for c in v)


def is_int(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


# ── the op digest (§3a) ───────────────────────────────────────────────────────


def op_digest(op: dict) -> str:
    """§3a: SHA-256 of the op's canonical text, every line ending in a newline. Raises ValueError if a field cannot be
    rendered as §3a states (a malformed op)."""
    kind = op.get("op")
    source = op.get("source")
    if kind not in DIGEST_HEADER or not isinstance(source, dict):
        raise ValueError("the op has no digestible kind or source")
    lines = [DIGEST_HEADER[kind]]
    for f in SOURCE_FIELDS:
        if not isinstance(source.get(f), str):
            raise ValueError(f"source.{f} is not a string")
        lines.append(f"{f}={source[f]}")
    for f in DIGEST_FIELDS[kind]:
        v = op.get(f)
        if f == "columns":
            if not isinstance(v, list) or not all(is_int(c) for c in v):
                raise ValueError("columns are not integers")
            text = ",".join(str(c) for c in v)
        elif f in ("a", "b", "operand"):
            if not isinstance(v, list) or not all(isinstance(h, str) for h in v):
                raise ValueError(f"{f} is not a list of strings")
            text = ",".join(v)
        elif f == "rank":
            if not is_int(v):
                raise ValueError("rank is not an integer")
            text = str(v)
        else:
            if not isinstance(v, str):
                raise ValueError(f"{f} is not a string")
            text = v
        lines.append(f"{f}={text}")
    origin = op.get("origin")
    if origin is not None and not isinstance(origin, str):
        raise ValueError("origin is not a string")
    lines.append("origin=" + ("-" if origin is None else "+" + origin))
    return hashlib.sha256("".join(line + "\n" for line in lines).encode("utf-8")).hexdigest()


# ── element targets (deltas): `bf16-rne-of-exact-sum` ─────────────────────────


def bf16_value(bits: int) -> Fraction:
    (x,) = struct.unpack("<f", struct.pack("<I", bits << 16))
    return Fraction(x)


def f32_value(bits: int) -> Fraction:
    (x,) = struct.unpack("<f", struct.pack("<I", bits))
    return Fraction(x)


def delta_as_binary32(delta) -> Fraction | None:
    """The binary32 value a ledger's `delta` denotes: its decimal read exactly and rounded once to binary32, ties to
    even, which is how a binary32 reader reads it. A writer prints a binary32 in the fewest digits that read back to
    it (`0.1` for 0x3dcccccd), so the decimal is not the binary32's own value and is not compared as one. `None`
    when it is beyond binary32."""
    decimal = getattr(delta, "decimal", None)
    try:
        return numconv.round_nearest_even(Fraction(delta if decimal is None else decimal), numconv.BINARY32)
    except numconv.Overflow:
        return None


def read_patch_removals(path: str) -> dict[str, list]:
    """The `remove_direction` ops of the `.vlp` at `path`, by tensor, in file order. They are what a v4 ledger does not
    carry (§3b): a tensor edited only by removals is recorded by its result bits, with the op's digest in `origins`.
    Ops of other kinds are not read from the patch: a low-rank op is in the ledger and a delta is its own edits."""
    with open(path, "rb") as f:
        patch = strict_json(f.read(), "the patch")
    operations = patch.get("operations") if isinstance(patch, dict) else None
    if not isinstance(operations, list):
        raise CannotEvaluate("the patch has no operations list")
    by_tensor: dict[str, list] = {}
    for op in operations:
        if isinstance(op, dict) and op.get("op") == OP_REMOVE and isinstance(op.get("tensor"), str):
            by_tensor.setdefault(op["tensor"], []).append(op)
    return by_tensor


def exact_sum_to_bf16(old_bits: int, delta_bits: int) -> int:
    """BF16 RNE of the exact sum of a BF16 and a binary32, once (no intermediate format). Zero signs follow IEEE-754
    addition: two zeros keep a negative sign only if both are negative, any other exact zero is +0, and a nonzero sum
    that rounds to zero keeps its own sign. Raises `numconv.Overflow`."""
    old, delta = bf16_value(old_bits), f32_value(delta_bits)
    exact = old + delta
    if exact == 0:
        both_zero = old == 0 and delta == 0
        negative = both_zero and bool(old_bits & 0x8000) and bool(delta_bits & 0x80000000)
        return 0x8000 if negative else 0
    rounded = numconv.round_nearest_even(exact, BF16_FMT)  # raises Overflow at 2^128
    if rounded == 0:
        return 0x8000 if exact < 0 else 0
    # `rounded` is a BF16 value, so it is exactly a binary64 and the encoder below does not round it again
    bits, over = V.f64_to_bf16(np.array([float(rounded)], dtype=np.float64))
    assert not over[0]
    return int(bits[0])


# ── the judgement ────────────────────────────────────────────────────────────


class Judge:
    def __init__(self, base: str, container: str):
        self.base_root, self.new_root = base, container
        #: `remove_direction` ops of the `.vlp` the caller supplied, by tensor; `None` when no patch was given.
        self.patch_ops: dict[str, list] | None = None
        self.patch: str | None = None
        self.recomputed_from_patch = 0
        self.L, self.N = Half(LEDGER), Half(NUMERICAL)
        self.engine: dict = {}
        self.digests_checked = 0
        self.patch_elements = 0
        self.not_established = ["the operands' origin (§3a covers the origin's text, not where the operands came from)",
                                "candidate.json (regenerated by every compile, not an authority: §7 step 4)",
                                "the content of re-derived (quantised) representations: digests are chained, the "
                                "tensors are not re-quantised"]

    # -- top level --------------------------------------------------------------
    def run(self) -> None:
        V.check_platform()
        self.base_files = file_digests(self.base_root)
        self.new_files = file_digests(self.new_root)
        try:
            self.bc = Store(self.base_root)
            self.nc = Store(self.new_root)
        except C.ContainerError as e:
            raise CannotEvaluate(f"a container fails the validating reader: {e}") from None
        new_index = strict_json(read_file(self.new_root, INDEX_FILE), INDEX_FILE)
        self.base_index = strict_json(read_file(self.base_root, INDEX_FILE), INDEX_FILE)
        self.new_index = new_index
        rel = new_index.get(LEDGER_POINTER)
        if not isinstance(rel, str):
            raise CannotEvaluate("the compiled container's index.json names no weight-patch ledger")
        C._safe_relpath(self.new_root, rel, "index.weight_patches")
        self.ledger_rel = rel
        ledger_bytes = read_file(self.new_root, rel)
        self.engine["ledger_sha256"] = hashlib.sha256(ledger_bytes).hexdigest()
        try:
            ledger = strict_json(ledger_bytes, "the ledger", parse_float=DecimalFloat)
        except ValueError as e:
            self.L.violate("ledger", f"the ledger is not valid JSON: {e}")
            self.N.cannot("the ledger cannot be read, so there are no ops to reconstruct")
            return
        if not isinstance(ledger, dict):
            self.L.violate("ledger", "the ledger is not a JSON object")
            self.N.cannot("the ledger cannot be read, so there are no ops to reconstruct")
            return
        schema = ledger.get("schema")
        self.engine.update(schema=schema, writer=ledger.get("writer"), rounding=ledger.get("rounding"))
        if schema != LEDGER_SCHEMA_V4:
            self.L.cannot(f"unknown ledger schema {schema!r}: this contract judges {LEDGER_SCHEMA_V4!r} only (§7 step 5)")
            self.N.cannot("the ledger is not a v4 ledger, so its ops are not reconstructed")
            return
        self.ledger = ledger
        self.L.judged = True
        if self.patch is not None:
            self.patch_ops = read_patch_removals(self.patch)
        self.judge()

    def judge(self) -> None:
        L, N = self.L, self.N
        lg = self.ledger
        self.base_index_sha = self.base_files[INDEX_FILE][1]
        targets = lg.get("targets")
        if not isinstance(targets, list) or not targets:
            L.violate("targets", "the ledger has no targets")
            N.cannot("the ledger has no targets")
            return
        reps = {t.get("representation") for t in targets if isinstance(t, dict)}
        if len(reps) != 1 or any(not isinstance(t, dict) for t in targets):
            L.cannot(f"targets name {len(reps)} representations; this contract judges one edited canonical "
                     "representation per ledger (the ledger's source names one canonical payload)")
            N.cannot("more than one edited representation")
            return
        (self.rep,) = reps
        if self.rep not in self.bc.reps or self.bc.reps[self.rep].get("compiled_from") \
                or self.bc.reps[self.rep]["encoding"] != BF16:
            L.violate("targets", f"representation {self.rep!r} is not a canonical BF16 representation of the base")
            N.cannot("the edited representation is not in the base")
            return
        if self.rep not in self.nc.reps:
            L.violate("targets", f"representation {self.rep!r} is absent from the compiled container")
            N.cannot("the edited representation is absent from the compiled container")
            return
        self.derived = sorted(r for r, e in self.bc.reps.items() if e.get("compiled_from") == self.rep)
        self.parse_judged_segments()
        self.stale = not self.check_source()
        if self.stale:
            N.cannot("the ledger is bound to another base (§7 step 5: a stale binding is refused), so its ops are not "
                     "recomputed against this one")
        plans = [self.plan_target(i, t) for i, t in enumerate(targets)]
        if not any(isinstance(t, dict) and "operations" in t for t in targets):
            L.violate("targets", "a v4 ledger is written only when at least one target is an operation target (§2)")
        self.check_work(plans)
        self.check_patch_elements(plans)
        for plan in plans:
            if plan is not None:
                self.compute_target(plan)
        self.check_rest(plans)
        self.check_result_digests()
        L.measure("targets", len(targets))
        L.measure("operations", sum(len(p["ops"]) for p in plans if p and p["kind"] == "operations"))
        L.measure("op digests recomputed and intact (§3a)", self.digests_checked)
        listed = set(lg.get("origins") or [])
        digests = [op.get("digest") for p in plans if p and p["kind"] == "operations" for op in p["raw_ops"]]
        L.measure("op digests listed in origins (informational: origins is not defined by v4)",
                  f"{sum(d in listed for d in digests)}/{len(digests)}")

    def parse_judged_segments(self) -> None:
        """Parse and verify the edited and re-derived segments of both containers (a failure is `could_not_evaluate`).
        Every other segment is held as a whole file: its bytes must hash to its own index entry's segment_sha256 in
        each container (otherwise the container is not intact), and check_files compares it with the base's file."""
        judged = {self.rep} | set(self.derived) | {r for r, e in self.nc.reps.items() if e.get("compiled_from") == self.rep}
        try:
            for store in (self.bc, self.nc):
                for rid in sorted(judged & set(store.reps)):
                    store.seg(rid)
        except C.ContainerError as e:
            raise CannotEvaluate(f"an edited or re-derived segment fails the validating reader: {e}") from None
        untouched = 0
        for store, files in ((self.bc, self.base_files), (self.nc, self.new_files)):
            for rid, e in store.reps.items():
                if rid in judged:
                    continue
                rel = "/".join(PurePosixPath(e["segment"]).parts)
                if rel not in files or files[rel][1] != e["segment_sha256"]:
                    raise CannotEvaluate(f"segment {rid}: the file does not hash to its index entry's segment_sha256")
                untouched += store is self.bc
        self.L.measure("untouched segments judged as whole files (byte-identical; internal structure not validated)", untouched)

    # -- §7 step 1: the source --------------------------------------------------
    def check_source(self) -> bool:
        L, src = self.L, self.ledger.get("source")
        if not isinstance(src, dict):
            L.violate("source", "the ledger has no source object")
            return False
        ok = True
        if src.get("index_sha256") != self.base_index_sha:
            L.violate("source.index_sha256", f"{str(src.get('index_sha256'))[:12]} is not the base's index.json "
                                             f"({self.base_index_sha[:12]}): bound to another base")
            ok = False
        if src.get("model") != self.base_index.get("model"):
            L.violate("source.model", f"{src.get('model')!r} is not the base's model {self.base_index.get('model')!r}")
            ok = False
        canon = src.get("canonical") or {}
        entry = self.bc.reps[self.rep]
        for field in CANONICAL_INDEX_FIELDS:
            if canon.get(field) != entry[field]:
                L.violate(f"source.canonical.{field}", f"is not the base's {self.rep} {field}")
                ok = False
        derived = src.get("derived")
        if not isinstance(derived, list):
            L.violate("source.derived", "is not a list")
            return False
        named = [d.get("representation") if isinstance(d, dict) else None for d in derived]
        if sorted(n for n in named if isinstance(n, str)) != self.derived or len(named) != len(self.derived):
            L.violate("source.derived", f"names {named}, the base re-derives {self.derived} from {self.rep}")
            ok = False
        for d in derived:
            rid = d.get("representation") if isinstance(d, dict) else None
            if rid in self.bc.reps:
                be = self.bc.reps[rid]
                for field in ("encoding", "payload_sha256", "segment_sha256", "encoder"):
                    if d.get(field) != be.get(field):
                        L.violate(f"source.derived[{rid}].{field}", "differs from the base's index.json")
                        ok = False
        return ok

    # -- §7 steps 2 and 5: each target and op, before any arithmetic ------------------
    def plan_target(self, i: int, t: dict):
        L, N = self.L, self.N
        name = t.get("tensor")
        label = f"targets[{i}] {name}"
        if not isinstance(name, str):
            L.violate(label, "the target names no tensor")
            return None
        has_ops, has_edits = "operations" in t, "edits" in t
        if has_ops == has_edits:
            L.violate(label, "a target must have exactly one of `operations` and `edits` (§3)")
            N.cannot(f"{label}: malformed target")
            return None
        allowed = OPERATION_TARGET_FIELDS if has_ops else ELEMENT_TARGET_FIELDS
        extra = set(t) - allowed
        if extra:
            L.violate(label, f"fields {sorted(extra)} do not belong on an {'operation' if has_ops else 'element'} "
                             "target (§3)")
            N.cannot(f"{label}: malformed target")
            return None
        bseg, nseg = self.bc.seg(self.rep), self.nc.seg(self.rep)
        if name not in bseg.by_name:
            L.violate(label, f"the base's {self.rep} has no tensor {name!r}")
            N.cannot(f"{label}: the tensor is not in the base")
            return None
        if name not in nseg.by_name:
            L.violate(label, "the compiled container has no such tensor")
            N.violate(label, "the edited tensor is absent from the compiled container")
            return None
        bshape = bseg.by_name[name].shape
        if t.get("object") != self.bc.reps[self.rep]["object"] or t.get("dtype") != BF16 \
                or t.get("shape") != list(bshape) or nseg.by_name[name].shape != bshape \
                or bseg.by_name[name].dtype != BF16 or len(bshape) != 2:
            L.violate(label, f"object/dtype/shape {t.get('object')!r}/{t.get('dtype')!r}/{t.get('shape')} do not "
                             f"match the base's {self.bc.reps[self.rep]['object']!r}/BF16/{list(bshape)} matrix, or "
                             "the compiled tensor's shape")
            N.cannot(f"{label}: the target does not describe the tensor")
            return None
        plan = {"label": label, "tensor": name, "shape": bshape, "target": t, "ops": [], "raw_ops": [],
                "kind": "operations" if has_ops else "edits", "refused": False}
        return self.plan_operations(plan) if has_ops else self.plan_edits(plan)

    def tensor_role(self, name: str):
        kind, prefixes = self.bc.objects[self.bc.reps[self.rep]["object"]]
        if kind == EMBEDDING_KIND or name.split(".")[-2:-1] == [EMBED_TOKENS_SUFFIX] \
                or any(p.endswith(EMBED_TOKENS_SUFFIX) for p in prefixes):
            return V.EMBED_TOKENS_ROLE
        return None

    def plan_operations(self, plan: dict) -> dict:
        L, N = self.L, self.N
        t, label, shape = plan["target"], plan["label"], plan["shape"]
        ops = t.get("operations")
        if not isinstance(ops, list) or not ops:
            L.violate(label, "an operation target with no operations")
            N.cannot(f"{label}: no operations")
            plan["refused"] = True
            return plan
        plan["raw_ops"] = [op for op in ops if isinstance(op, dict)]
        kinds = [op.get("op") if isinstance(op, dict) else None for op in ops]
        if all(k in OP_FIELDS for k in kinds) and OP_LOW_RANK not in kinds:
            L.violate(label, "an operation target without an add_low_rank_columns op must be an element target (§2)")
        for field in ("base_tensor_sha256", "result_tensor_sha256"):
            if not is_sha(t.get(field)):
                L.violate(label, f"{field} is not a SHA-256")
        if not is_int(t.get("changed_elements")) or t["changed_elements"] < 0:
            L.violate(label, "changed_elements is not a non-negative integer")
        rows, cols = shape
        if rows * cols > MAX_STRUCTURED_TENSOR_ELEMENTS:
            L.violate(label, f"{rows}x{cols} exceeds MAX_STRUCTURED_TENSOR_ELEMENTS {MAX_STRUCTURED_TENSOR_ELEMENTS}")
            plan["refused"] = True
        source = {"model": self.ledger["source"].get("model") if isinstance(self.ledger.get("source"), dict) else None,
                  "index_sha256": self.base_index_sha, "representation": self.rep,
                  "payload_sha256": self.bc.reps[self.rep]["payload_sha256"]}
        footprint: dict[int, int] = {}
        for j, op in enumerate(ops):
            where = f"{label} op {j}"
            parsed = self.plan_op(where, op, plan["tensor"], shape, source)
            if parsed is None:
                plan["refused"] = True
                continue
            for c in parsed.columns:
                if c in footprint:
                    L.violate(where, f"column {c} is also written by op {footprint[c]}: the ops of one target must "
                                     "have pairwise disjoint columns (§4)")
                    plan["refused"] = True
                    break
            for c in parsed.columns:
                footprint.setdefault(c, j)
            plan["ops"].append((j, op, parsed))
        if plan["refused"]:
            N.cannot(f"{label}: an op is refused (see the ledger half), so the tensor is not reconstructed")
        return plan

    def plan_op(self, where: str, op, tensor: str, shape, source: dict, from_patch: bool = False):
        """`from_patch`: the op is read from a `.vlp`, not from the ledger, so it carries no `operands_sha256` and no
        `changed_elements`. Every other check is the same."""
        L = self.L
        if not isinstance(op, dict):
            L.violate(where, "the op is not an object")
            return None
        kind = op.get("op")
        if kind not in OP_FIELDS:
            L.cannot(f"{where}: op {kind!r} is not one this contract supports ({sorted(OP_FIELDS)})")
            return None
        extra = set(op) - (OP_FIELDS[kind] - LEDGER_OP_FIELDS if from_patch else OP_FIELDS[kind])
        if extra:
            L.cannot(f"{where}: unsupported op fields {sorted(extra)}")
            return None
        if op.get("tensor") != tensor:
            L.violate(where, f"the op names tensor {op.get('tensor')!r}, the target {tensor!r}")
            return None
        if op.get("source") != source:
            got = op.get("source") if isinstance(op.get("source"), dict) else {}
            fields = [f for f in SOURCE_FIELDS if got.get(f) != source[f]] or ["fields"]
            L.violate(where, f"stale or foreign source binding ({', '.join(fields)}): the op is not bound to this base")
            return None
        if op.get("numerics") not in V.PROFILES:
            L.cannot(f"{where}: numerics profile {op.get('numerics')!r} is not one this contract implements")
            return None
        # §5 bounds, before any parsing of operand values or arithmetic
        if kind == OP_LOW_RANK:
            rank = op.get("rank")
            if is_int(rank) and rank > MAX_STRUCTURED_RANK:
                L.violate(where, f"rank {rank} exceeds MAX_STRUCTURED_RANK {MAX_STRUCTURED_RANK} (§5)")
                return None
            n = (len(op["a"]) if isinstance(op.get("a"), list) else 0) + \
                (len(op["b"]) if isinstance(op.get("b"), list) else 0)
        else:
            n = (len(op["operand"]) if isinstance(op.get("operand"), list) else 0) + 1
        if n > MAX_STRUCTURED_OPERAND_ELEMENTS:
            L.violate(where, f"{n} operand elements exceed MAX_STRUCTURED_OPERAND_ELEMENTS "
                             f"{MAX_STRUCTURED_OPERAND_ELEMENTS} (§5)")
            return None
        try:
            intact = op_digest(op) == op.get("digest")
        except ValueError as e:
            L.violate(where, f"malformed op: {e}")
            return None
        if not intact:
            L.violate(where, "digest is not intact: the op's fields do not hash to its recorded digest (§3a)")
            return None
        self.digests_checked += 1
        try:
            parsed = V.LowRank(op, shape) if kind == OP_LOW_RANK else V.RemoveDirection(op, shape, u_key="operand")
        except V.Refusal as e:
            L.violate(where, f"the op must be refused: {e.code} ({e.detail})")
            return None
        parsed.kind = kind
        if from_patch:
            return parsed
        recorded = op.get("operands_sha256")
        keys = OPERAND_KEYS[kind]
        sound = True
        if not isinstance(recorded, dict) or set(recorded) != set(keys):
            L.violate(where, f"operands_sha256 must have exactly the keys {list(keys)}")
            sound = False
        else:
            for key, data in parsed.operand_digests().items():
                if recorded[key] != hashlib.sha256(data).hexdigest():
                    L.violate(where, f"operands_sha256.{key} does not match the op's {key}")
                    sound = False
        if not is_int(op.get("changed_elements")) or op["changed_elements"] < 0:
            L.violate(where, "changed_elements is not a non-negative integer")
        # §7a: an operand digest that contradicts the operands leaves nothing trustworthy to recompute
        return parsed if sound else None

    def plan_edits(self, plan: dict) -> dict:
        L, N = self.L, self.N
        edits, label = plan["target"].get("edits"), plan["label"]
        rows, cols = plan["shape"]
        if not isinstance(edits, list) or not edits:
            L.violate(label, "an element target with no edits")
            N.cannot(f"{label}: no edits")
            plan["refused"] = True
            return plan
        self.patch_elements += len(edits)
        seen, parsed = set(), []
        for k, e in enumerate(edits):
            where = f"{label} edit {k}"
            if not isinstance(e, dict) or set(e) - EDIT_FIELDS or not all(
                    is_int(e.get(f)) for f in ("row", "col", "old_bits", "new_bits", "delta_bits")) \
                    or not isinstance(e.get("delta"), (int, float)) or isinstance(e.get("delta"), bool):
                L.violate(where, "malformed edit")
                plan["refused"] = True
                continue
            if not (0 <= e["row"] < rows and 0 <= e["col"] < cols) or not (0 <= e["old_bits"] < 1 << 16) \
                    or not (0 <= e["new_bits"] < 1 << 16) or not (0 <= e["delta_bits"] < 1 << 32):
                L.violate(where, "an edit outside the tensor, or bits out of range")
                plan["refused"] = True
                continue
            if (e["row"], e["col"]) in seen:
                L.violate(where, f"element ({e['row']}, {e['col']}) is edited twice")
                plan["refused"] = True
                continue
            seen.add((e["row"], e["col"]))
            enc = e.get("encoding")
            if enc not in (None, DELTA_ENCODING, RESULT_BITS):
                L.cannot(f"{where}: unknown edit encoding {enc!r}")
                plan["refused"] = True
                continue
            parsed.append(e)
        plan["edits"] = parsed
        if plan["refused"]:
            N.cannot(f"{label}: a malformed edit (see the ledger half), so the tensor is not reconstructed")
            return plan
        if self.patch_ops is not None and any(e.get("encoding") == RESULT_BITS for e in parsed):
            self.plan_patch_removals(plan)
        return plan

    def plan_patch_removals(self, plan: dict) -> None:
        """A result-bits element target, with the patch in hand: admit the patch's `remove_direction` ops on this
        tensor exactly as a ledger's ops are admitted (§5, §3a), and require each to be one this compile was assembled
        from (its digest among the ledger's `origins`). The ops then make the tensor recomputable (§3b)."""
        L, N = self.L, self.N
        label, shape = plan["label"], plan["shape"]
        ops = self.patch_ops.get(plan["tensor"], [])
        if not ops:
            return  # nothing to recompute from: expected_edits says so
        if any(e.get("encoding") != RESULT_BITS for e in plan["edits"]):
            L.cannot(f"{label}: an element target mixes delta and result-bits edits; a tensor takes one form")
            N.cannot(f"{label}: mixed edit forms")
            plan["refused"] = True
            return
        src = self.ledger.get("source")
        source = {"model": src.get("model") if isinstance(src, dict) else None,
                  "index_sha256": self.base_index_sha, "representation": self.rep,
                  "payload_sha256": self.bc.reps[self.rep]["payload_sha256"]}
        origins = self.ledger.get("origins")
        origins = set(origins) if isinstance(origins, list) and all(isinstance(o, str) for o in origins) else set()
        footprint: dict[int, int] = {}
        for j, op in enumerate(ops):
            where = f"{label} patch op {j}"
            parsed = self.plan_op(where, op, plan["tensor"], shape, source, from_patch=True)
            if parsed is None:
                plan["refused"] = True
                continue
            if op.get("digest") not in origins:
                L.violate(where, "the op's digest is not among the ledger's origins: the patch is not the one this "
                                 "container was compiled from")
                plan["refused"] = True
                continue
            for c in parsed.columns:
                if c in footprint:
                    L.violate(where, f"column {c} is also written by patch op {footprint[c]}: the ops of one tensor "
                                     "must have pairwise disjoint columns (§4)")
                    plan["refused"] = True
                    break
            for c in parsed.columns:
                footprint.setdefault(c, j)
            plan["ops"].append((j, op, parsed))
        if plan["refused"]:
            plan["ops"] = []
            N.cannot(f"{label}: a patch op is refused (see the ledger half), so the tensor is not reconstructed")

    def check_patch_elements(self, plans) -> None:
        """§3b: all element targets together list at most MAX_PATCH_ELEMENTS elements (inclusive)."""
        self.L.measure("element-target elements (§3b)", f"{self.patch_elements} of {MAX_PATCH_ELEMENTS}")
        if self.patch_elements > MAX_PATCH_ELEMENTS:
            self.L.violate("ledger", f"element targets list {self.patch_elements} elements, over MAX_PATCH_ELEMENTS "
                                     f"{MAX_PATCH_ELEMENTS} (§3b)")
            for plan in plans:
                if plan and plan["kind"] == "edits" and not plan["refused"]:
                    plan["refused"] = True
                    self.N.cannot(f"{plan['label']}: the element targets exceed MAX_PATCH_ELEMENTS")

    def check_work(self, plans) -> None:
        # Removals read from a supplied patch count too: §5 bounds one compile's structured ops together.
        work = sum(p.work() for plan in plans if plan for _, _, p in plan["ops"])
        self.L.measure("structured work (multiply-adds, §5)", f"{work} of {MAX_STRUCTURED_WORK}")
        if work > MAX_STRUCTURED_WORK:
            self.L.violate("ledger", f"the structured ops need {work} multiply-adds, over MAX_STRUCTURED_WORK "
                                     f"{MAX_STRUCTURED_WORK} (§5)")
            for plan in plans:
                if plan and plan["ops"] and not plan["refused"]:
                    plan["refused"] = True
                    self.N.cannot(f"{plan['label']}: the compile exceeds MAX_STRUCTURED_WORK, so nothing is recomputed")

    # -- §7 step 3 (and 6): recompute and compare every element -----------------------
    def compute_target(self, plan: dict) -> None:
        L, N = self.L, self.N
        label, name, (rows, cols) = plan["label"], plan["tensor"], plan["shape"]
        base, base_raw, _ = tensor_bits(self.bc, self.rep, name)
        new, new_raw, _ = tensor_bits(self.nc, self.rep, name)
        plan["base_raw"], plan["new_raw"] = base_raw, new_raw
        base2d, new2d = base.reshape(rows, cols), new.reshape(rows, cols)
        t = plan["target"]
        if plan["kind"] == "operations":
            base_sha, new_sha = hashlib.sha256(base_raw).hexdigest(), hashlib.sha256(new_raw).hexdigest()
            if t.get("base_tensor_sha256") != base_sha:
                L.violate(label, f"base_tensor_sha256 is not the base tensor's digest ({base_sha[:12]})")
            if t.get("result_tensor_sha256") != new_sha:
                L.violate(label, f"result_tensor_sha256 is not the compiled tensor's digest ({new_sha[:12]})")
        if plan["refused"] or self.stale:
            return
        expected = self.expected_operations(plan, base2d) if plan["kind"] == "operations" \
            else self.expected_edits(plan, base2d, new2d)
        if expected is None:
            return
        footprint = np.zeros(cols, dtype=bool)
        for _, _, p in plan["ops"]:
            footprint[p.columns] = True
        self.compare(label, base2d, new2d, expected, footprint)

    def expected_operations(self, plan: dict, base2d: np.ndarray):
        L, N = self.L, self.N
        t, label = plan["target"], plan["label"]
        expected = base2d.copy()
        role = self.tensor_role(plan["tensor"])
        computed_total, recorded_total, sham = 0, 0, True
        for j, op, parsed in plan["ops"]:
            where = f"{label} op {j}"
            try:
                result = parsed.apply(base2d, tensor_shape=plan["shape"], tensor_role=role)  # each op on the BASE (§4)
            except V.Refusal as e:
                L.violate(where, f"the op must be refused: {e.code} ({e.detail})")
                N.cannot(f"{where}: refused ({e.code}), so the tensor is not reconstructed")
                return None
            cols = np.asarray(parsed.columns, dtype=np.int64)
            expected[:, cols] = result[:, cols]
            changed = int(np.count_nonzero(result[:, cols] != base2d[:, cols]))
            computed_total += changed
            recorded = op.get("changed_elements")
            recorded_total += recorded if is_int(recorded) else 0
            zero = parsed.kind == OP_LOW_RANK and parsed.zero_valued()
            sham = sham and zero
            if zero and changed:
                raise AssertionError("a zero-valued op changed an element")  # the selection makes this impossible
            if recorded != changed:
                what = "a zero-valued op (§4a) never changes an element" if zero else "recomputed"
                L.violate(where, f"changed_elements {recorded} != {changed} ({what})")
            if not zero and changed == 0:
                L.violate(where, "the op changes no element and is not zero-valued: an edit not declared as an "
                                 "identity must change something, so it must be refused (§4a)")
        if t.get("changed_elements") != recorded_total:
            L.violate(label, f"changed_elements {t.get('changed_elements')} is not the sum of its ops' "
                             f"({recorded_total})")
        if t.get("changed_elements") != computed_total:
            L.violate(label, f"changed_elements {t.get('changed_elements')} != {computed_total} recomputed")
        if sham:
            self.shams += 1
            if t.get("result_tensor_sha256") != t.get("base_tensor_sha256"):
                L.violate(label, "a sham (every op zero-valued) must record result_tensor_sha256 = base_tensor_sha256")
        elif computed_total == 0 or t.get("result_tensor_sha256") == t.get("base_tensor_sha256"):
            L.violate(label, "the result must differ from the base unless the target is a sham (§6)")
        self.expected_changes += computed_total
        return expected

    def expected_from_patch(self, plan: dict, base2d: np.ndarray):
        """A result-bits element target recomputed from the supplied patch's `remove_direction` ops: each op on the
        base, its columns joined (§4), and the ledger's edits held to exactly the elements that change."""
        L, N = self.L, self.N
        label = plan["label"]
        expected = base2d.copy()
        role = self.tensor_role(plan["tensor"])
        for j, _, parsed in plan["ops"]:
            where = f"{label} patch op {j}"
            try:
                result = parsed.apply(base2d, tensor_shape=plan["shape"], tensor_role=role)
            except V.Refusal as e:
                L.violate(where, f"the op must be refused: {e.code} ({e.detail})")
                N.cannot(f"{where}: refused ({e.code}), so the tensor is not reconstructed")
                return None
            cols = np.asarray(parsed.columns, dtype=np.int64)
            if not np.any(result[:, cols] != base2d[:, cols]):
                L.violate(where, "the op changes no element: it must be refused, not compiled")
            expected[:, cols] = result[:, cols]
        recorded = {(e["row"], e["col"]): e for e in plan["edits"]}
        changed = {(int(r), int(c)) for r, c in zip(*np.nonzero(expected != base2d))}
        for r, c in sorted(changed - set(recorded))[:OFFENDING_LIMIT]:
            L.violate(f"{label} ({r}, {c})", "the patch's ops change this element and the ledger does not record it")
        for (r, c), e in recorded.items():
            where = f"{label} ({r}, {c})"
            if e["old_bits"] != int(base2d[r, c]):
                L.violate(where, f"old_bits {e['old_bits']:04x} is not the base's {int(base2d[r, c]):04x}")
            if (r, c) not in changed:
                L.violate(where, "the ledger records an edit the patch's ops do not make")
            elif e["new_bits"] != int(expected[r, c]):
                L.violate(where, f"new_bits {e['new_bits']:04x} is not the recomputed {int(expected[r, c]):04x}")
        self.expected_changes += len(changed)
        self.recomputed_from_patch += 1
        return expected

    def expected_edits(self, plan: dict, base2d: np.ndarray, new2d: np.ndarray):
        L, N = self.L, self.N
        label = plan["label"]
        if plan["ops"]:
            return self.expected_from_patch(plan, base2d)
        expected = base2d.copy()
        recomputable = True
        for e in plan["edits"]:
            r, c = e["row"], e["col"]
            where = f"{label} ({r}, {c})"
            if e["old_bits"] != int(base2d[r, c]):
                L.violate(where, f"old_bits {e['old_bits']:04x} is not the base's {int(base2d[r, c]):04x}")
            if e.get("encoding") == RESULT_BITS:
                # The ledger records the result of an op it does not record: nothing to recompute it from.
                recomputable = False
                expected[r, c] = e["new_bits"]
                continue
            if self.ledger.get("rounding") != DELTA_ROUNDING:
                L.cannot(f"{where}: delta rounding {self.ledger.get('rounding')!r} is not {DELTA_ROUNDING!r}")
                recomputable = False
                continue
            if (e["delta_bits"] & V.F32_EXP_MASK) == V.F32_EXP_MASK:
                # Checked before anything reads the bits as a number: an infinity or a NaN has no value to compare.
                L.violate(where, f"delta_bits {e['delta_bits']:08x} is not finite: the delta must be refused")
                recomputable = False
                continue
            if delta_as_binary32(e["delta"]) != f32_value(e["delta_bits"]):
                L.violate(where, f"delta {e['delta']!r} does not read as the binary32 of delta_bits "
                                 f"{e['delta_bits']:08x}")
            if (int(base2d[r, c]) & V.BF16_EXP_MASK) == V.BF16_EXP_MASK:
                L.violate(where, "the base element is not finite: the delta must be refused")
                recomputable = False
                continue
            try:
                want = exact_sum_to_bf16(int(base2d[r, c]), e["delta_bits"])
            except numconv.Overflow:
                L.violate(where, "the sum overflows BF16: the delta must be refused")
                recomputable = False
                continue
            if e["new_bits"] != want:
                L.violate(where, f"new_bits {e['new_bits']:04x} is not the recomputed {want:04x}")
            expected[r, c] = want
            self.expected_changes += int(want != int(base2d[r, c]))
        if not recomputable:
            # Still hold the container to what the ledger says it wrote, under the ledger half.
            mism = int(np.count_nonzero(new2d != expected))
            if mism:
                L.violate(label, f"{mism} elements differ from the base with the ledger's recorded bits", mism)
            why = "and the patch given holds no remove_direction op on this tensor" if self.patch_ops is not None \
                else "so its numerics cannot be recomputed from the ledger alone; give the patch to recompute them"
            N.cannot(f"{label}: an element target records result bits of an op that is not in the ledger, {why}")
            return None
        return expected

    def compare(self, label: str, base2d, new2d, expected, footprint) -> None:
        self.N.judged = True
        rows, cols = base2d.shape
        self.elements_compared += rows * cols
        bad = new2d != expected
        count = int(np.count_nonzero(bad))
        if not count:
            return
        changed = expected != base2d
        inside = np.broadcast_to(footprint[None, :], bad.shape)
        written_bad = int(np.count_nonzero(bad & changed))
        untouched_bad = int(np.count_nonzero(bad & ~changed & inside))
        outside_bad = int(np.count_nonzero(bad & ~inside))
        i = int(np.flatnonzero(bad.reshape(-1))[0])
        r, c = divmod(i, cols)
        self.N.violate(label, f"{count} elements differ from the recomputed tensor ({written_bad} that the ops change, "
                              f"{untouched_bad} inside the footprint whose expected bits are the "
                              f"base's, {outside_bad} outside it); first at {position(i, cols)}: expected {int(expected[r, c]):04x}, found "
                              f"{int(new2d[r, c]):04x}", count)

    # -- §7 step 4: everything else ---------------------------------------------------
    def check_rest(self, plans) -> None:
        L = self.L
        names = {p["tensor"] for p in plans if p}
        bseg, nseg = self.bc.seg(self.rep), self.nc.seg(self.rep)
        if [(e.name, e.dtype, e.shape, e.offset, e.len) for e in bseg.tensors] != \
                [(e.name, e.dtype, e.shape, e.offset, e.len) for e in nseg.tensors] \
                or segment_header(bseg) != segment_header(nseg):
            L.violate(f"{self.rep} segment header", "the edited segment's header differs from the base's")
        seen = set()
        for p in plans:
            if p:
                if p["tensor"] in seen:
                    L.violate(p["label"], "the tensor is the subject of more than one target")
                seen.add(p["tensor"])
        others = 0
        for e in bseg.tensors:
            if e.name in names or e.name not in nseg.by_name:
                if e.name not in nseg.by_name:
                    L.violate(f"{self.rep}/{e.name}", "absent from the compiled container")
                continue
            others += 1
            braw, nraw = self.bc.read(self.rep, e.name), self.nc.read(self.rep, e.name)
            if braw != nraw:
                if e.dtype == BF16 and len(braw) == len(nraw):
                    b, n = np.frombuffer(braw, "<u2"), np.frombuffer(nraw, "<u2")
                    diff = np.flatnonzero(b != n)
                    cols = e.shape[-1] if e.shape else 1
                    L.violate(f"{self.rep}/{e.name}", f"a tensor the ledger does not edit differs from the base in "
                                                      f"{diff.size} elements, first at {position(int(diff[0]), cols)}",
                              int(diff.size))
                else:
                    L.violate(f"{self.rep}/{e.name}", "a tensor the ledger does not edit differs from the base")
        L.measure("tensors of the edited representation compared byte for byte", others)
        self.check_index()
        self.check_files()
        self.check_derived()

    def check_index(self) -> None:
        L = self.L
        base, new = self.base_index, self.new_index
        allowed = {(LEDGER_POINTER,)}
        allowed |= {("representations", self.rep, f) for f in CANONICAL_INDEX_FIELDS}
        allowed |= {("representations", r, f) for r in self.derived for f in DERIVED_INDEX_FIELDS}
        diffs = []

        def walk(a, b, path):
            if isinstance(a, dict) and isinstance(b, dict):
                for k in sorted(set(a) | set(b)):
                    p = path + (k,)
                    if p in allowed:
                        continue
                    if k not in a or k not in b:
                        diffs.append(p)
                    else:
                        walk(a[k], b[k], p)
            elif a != b or type(a) is not type(b):
                diffs.append(path)

        walk(base, new, ())
        for p in diffs:
            L.violate(f"index.json {'.'.join(map(str, p))}", "differs from the base; a compile may change only the "
                                                             "edited and re-derived representations' digests and the "
                                                             "ledger pointer")

    def check_files(self) -> None:
        L = self.L
        segs = {self.bc.reps[self.rep]["segment"]} | {self.bc.reps[r]["segment"] for r in self.derived}
        may_change = set(FILES_THAT_MAY_CHANGE) | {self.ledger_rel} | segs
        for rel in sorted(set(self.base_files) | set(self.new_files)):
            if rel in NOT_JUDGED_FILES:
                continue
            if rel == self.ledger_rel and rel not in self.base_files:
                continue
            if rel not in self.base_files or rel not in self.new_files:
                L.violate(rel, "present in only one of the containers")
            elif rel not in may_change and self.base_files[rel] != self.new_files[rel]:
                L.violate(rel, "a file outside the edited and re-derived segments differs from the base; §7 step 4 "
                               "permits only index.json and the ledger to change")
        L.measure("files compared", len(self.base_files))

    def check_derived(self) -> None:
        """§7 step 4: the re-derived representations name the compiled canonical payload. Digests only: they are not
        re-quantised."""
        L = self.L
        canon_now = self.nc.reps[self.rep]["payload_sha256"]  # the reader checked it against the segment's bytes
        now = sorted(r for r, e in self.nc.reps.items() if e.get("compiled_from") == self.rep)
        if now != self.derived:
            L.violate("derived representations", f"compiled container re-derives {now}, the base {self.derived}")
        identical, total = 0, 0
        for rid in self.derived:
            if rid not in self.nc.reps:
                continue
            e = self.nc.reps[rid]
            if e.get("source_representation_digest") != canon_now:
                L.violate(f"index.json {rid}", "source_representation_digest is not the compiled canonical payload")
            b, n = self.bc.seg(rid), self.nc.seg(rid)
            if [(t.name, t.dtype, t.shape) for t in b.tensors] != [(t.name, t.dtype, t.shape) for t in n.tensors]:
                L.violate(f"{rid} segment", "the re-derived representation's tensor table differs from the base's")
                continue
            for t in b.tensors:
                total += 1
                identical += self.bc.read(rid, t.name) == self.nc.read(rid, t.name)
        if total:
            L.measure("re-derived tensors byte-identical to the base (informational)", f"{identical}/{total}")

    def check_result_digests(self) -> None:
        L, res = self.L, self.ledger.get("result")
        if not isinstance(res, dict):
            L.violate("result", "the ledger has no result object")
            return
        canon, entry = res.get("canonical") or {}, self.nc.reps[self.rep]
        for field in CANONICAL_INDEX_FIELDS:
            if canon.get(field) != entry[field]:
                L.violate(f"result.canonical.{field}", f"is not the compiled {self.rep} {field}")
        derived = res.get("derived")
        if not isinstance(derived, list):
            L.violate("result.derived", "is not a list")
            return
        named = sorted(d.get("representation") for d in derived if isinstance(d, dict)
                       and isinstance(d.get("representation"), str))
        if named != self.derived or len(derived) != len(self.derived):
            L.violate("result.derived", f"names {named}, the compile re-derives {self.derived}")
        for d in derived:
            rid = d.get("representation") if isinstance(d, dict) else None
            if rid not in self.nc.reps:
                continue
            ne = self.nc.reps[rid]
            for field in ("encoding", "payload_sha256", "segment_sha256", "encoder", "source_representation_digest"):
                if d.get(field) != ne.get(field):
                    L.violate(f"result.derived[{rid}].{field}", "differs from the compiled index.json")
            if d.get("source_representation_digest") != entry["payload_sha256"]:
                L.violate(f"result.derived[{rid}]", "does not derive from the compiled canonical payload")
        self.engine["encoders"] = {d.get("representation"): d.get("encoder") for d in derived if isinstance(d, dict)}


def could_not(out: dict, *reasons: str) -> dict:
    out.update(status="could_not_evaluate", violations=0, offending=[], reasons=list(reasons))
    return out


def evaluate(out: dict, base: str, container: str, patch: str | None = None) -> dict:
    """Fill `out` with the two verdicts and the combined status. Never raises for a bad input. `patch`, when given, is
    the `.vlp` the container was compiled from: it supplies the `remove_direction` ops a v4 ledger records only by
    their result bits (§3b), so those tensors can be recomputed too."""
    out["recomputed_from"] = ("the base container's weights and the operands the compiled container's ledger records; "
                              "the ledger's hashes and counts are checked, never used as expected values")
    if patch is not None:
        out["recomputed_from"] += ("; for a tensor the ledger records only by result bits, the remove_direction ops of "
                                   "the patch given, each held to the ledger's origins")
    judge = Judge(base, container)
    judge.patch = patch
    judge.recomputed_from_patch = 0
    judge.shams = 0
    judge.expected_changes = 0
    judge.elements_compared = 0
    try:
        judge.run()
    except CannotEvaluate as e:
        judge.L.cannot(str(e))
        judge.N.cannot(str(e))
    except RuntimeError as e:
        judge.L.cannot(f"the platform cannot run the profiles: {e}")
        judge.N.cannot(f"the platform cannot run the profiles: {e}")
    except BAD_INPUT as e:
        reason = f"an input can't be read: {type(e).__name__}: {e}"
        judge.L.cannot(reason)
        judge.N.cannot(reason)
    N, L = judge.N, judge.L
    N.measure("elements compared", judge.elements_compared)
    N.measure("elements expected to change", judge.expected_changes)
    N.measure("sham targets (every op zero-valued)", judge.shams)
    if patch is not None:
        N.measure("result-bits targets recomputed from the patch given", judge.recomputed_from_patch)
    halves = {NUMERICAL: N.report(), LEDGER: L.report()}
    stale = getattr(judge, "stale", None)
    digest_findings = any("digest is not intact" in o["detail"] for o in L.offending)
    digest_state = "violated" if digest_findings else "satisfied" if judge.digests_checked else "could_not_evaluate"
    binding = "could_not_evaluate" if stale is None else "violated" if stale else "satisfied"
    statuses = [h["status"] for h in halves.values()]
    status = "satisfied" if all(s == "satisfied" for s in statuses) else \
        "violated" if "violated" in statuses else "could_not_evaluate"
    offending = sorted(N.offending + L.offending, key=lambda o: -o["violations"])
    if len(offending) > OFFENDING_LIMIT:  # the protocol: `offending` sums to `violations`, so fold the tail into one
        tail = offending[OFFENDING_LIMIT - 1:]
        offending = offending[:OFFENDING_LIMIT - 1] + [{
            "name": f"{len(tail)} further findings", "violations": sum(o["violations"] for o in tail),
            "detail": "listed in full under `verdicts`", "half": ",".join(sorted({o["half"] for o in tail}))}]
    out.update(
        status=status,
        violations=N.violations() + L.violations() if status == "violated" else 0,
        offending=offending if status == "violated" else [],
        reasons=[f"{NUMERICAL}: {r}" for r in N.reasons] + [f"{LEDGER}: {r}" for r in L.reasons],
        verdicts=halves,
        failed_halves=[k for k, h in halves.items() if h["status"] != "satisfied"],
        numerical_satisfaction=halves[NUMERICAL]["status"],
        ledger_integrity=halves[LEDGER]["status"],
        provenance=halves[LEDGER]["status"],
        provenance_detail={"base_binding": binding, "op_digest": digest_state, "operand_origin": NOT_CHECKED},
        engine_reported=judge.engine,
        measurements=N.measurements + L.measurements + [{"name": "not established",
                                                         "value": "; ".join(judge.not_established)}],
    )
    if status == "could_not_evaluate" and not out["reasons"]:
        out["reasons"] = ["nothing was judged"]
    files = (getattr(judge, "base_files", None), getattr(judge, "new_files", None))
    if files[0] is not None:
        out["base"]["sha256"] = container_digest(files[0])
    if files[1] is not None:
        out["container"]["sha256"] = container_digest(files[1])
    return out
