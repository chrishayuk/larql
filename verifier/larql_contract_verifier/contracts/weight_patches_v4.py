class CannotEvaluate(Exception):
    """Nothing can be judged (an input can't be read, or the ledger is of an unknown schema)."""


class Half:
    """One verdict: what broke it (`offending`), what stopped it being evaluated (`reasons`), and what was measured."""

    def __init__(self, name: str):
        self.name = name
        self.offending: list[dict] = []
        self.reasons: list[str] = []
        self.measurements: list[dict] = []
        self.judged = False

    def violate(self, name: str, detail: str, count: int = 1) -> None:
        self.offending.append({"name": name, "violations": int(count), "detail": detail, "half": self.name})

    def cannot(self, reason: str) -> None:
        self.reasons.append(reason)

    def measure(self, name: str, value) -> None:
        self.measurements.append({"name": name, "value": str(value)})

    def violations(self) -> int:
        return sum(o["violations"] for o in self.offending)

    def status(self) -> str:
        if self.offending:
            return "violated"
        if self.reasons or not self.judged:
            return "could_not_evaluate"
        return "satisfied"

    def report(self) -> dict:
        off = sorted(self.offending, key=lambda o: -o["violations"])
        return {"status": self.status(), "violations": self.violations(), "offending": off[:OFFENDING_LIMIT],
                "offending_total": len(off), "reasons": list(self.reasons), "measurements": list(self.measurements)}


