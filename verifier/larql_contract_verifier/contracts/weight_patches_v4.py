class DecimalFloat(float):
    """A JSON number with a fraction or exponent: the binary64 `json` would give, plus the decimal as written. The
    binary64 is already a rounded reading, and a `delta` is judged as the binary32 its decimal denotes (§3b)."""

    def __new__(cls, text: str):
        value = super().__new__(cls, text)
        value.decimal = Decimal(text)
        return value


def strict_json(data: bytes, what: str, parse_float=float):
    """JSON with no duplicate keys and no NaN/Infinity constants."""

    def pairs(items):
        d = {}
        for k, v in items:
            if k in d:
                raise ValueError(f"{what}: duplicate JSON key {k!r}")
            d[k] = v
        return d

    def const(name):
        raise ValueError(f"{what}: non-finite JSON constant {name}")

    return json.loads(data.decode("utf-8"), object_pairs_hook=pairs, parse_constant=const, parse_float=parse_float)


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


def file_digests(root: str) -> dict[str, tuple[int, str]]:
    """`{relative path: (size, sha256)}` of every regular file under `root`. A symlink is refused: the comparison of
    files and the container digest must cover the bytes that are actually there."""
    out = {}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames.sort()
        for name in sorted(filenames + [d for d in dirnames if os.path.islink(os.path.join(dirpath, d))]):
            p = os.path.join(dirpath, name)
            if os.path.islink(p):
                raise CannotEvaluate(f"{p} is a symlink; this contract reads regular files only")
            rel = os.path.relpath(p, root).replace(os.sep, "/")
            out[rel] = (os.path.getsize(p), sha256_file(p))
    return out


def container_digest(files: dict[str, tuple[int, str]]) -> str:
    """The package's container digest (`checkpoint.container_sha256`): sorted `<path>\\0<size>\\0<sha256>\\n` lines."""
    lines = sorted(f"{rel}\0{size}\0{sha}\n" for rel, (size, sha) in files.items())
    return hashlib.sha256("".join(lines).encode()).hexdigest()


class Store:
    """A container as this contract reads it: `index.json`'s representations, each segment's tensor table, and the
    graph objects' kinds and tensor prefixes.

    It applies the generic MUST-reject rules of `refcheck.container` (index version, required representation fields,
    `<object>@<encoding>` keys, objects present in the graph, BF16 or the exact Q8_0 codec only) to every
    representation, and that module's own segment parser and digest check (framing, contiguity, lengths, counts, unique
    names, both digests) on demand, through `seg`, only to the segments this contract parses: the edited and
    re-derived ones (§7 step 4). It does not apply that reader's Qwen3-0.6B profile rules that are not about framing,
    such as exactly one source binding per graph object, which Gemma 3's vision objects do not meet."""

    def __init__(self, root: str):
        root = os.path.abspath(root)
        self.root = root
        index = C._read_json_file(os.path.join(root, INDEX_FILE), INDEX_FILE)
        if not isinstance(index, dict) or not is_int(index.get("version")) or index["version"] != C.INDEX_VERSION:
            raise C.ContainerError(f"index.json version is not {C.INDEX_VERSION}")
        for refused in ("moe_manifest", "auxiliary_references"):
            if refused in index:
                raise C.ContainerError(f"index.json has {refused}, outside what this contract reads")
        if "system_graph" not in index:
            raise C.ContainerError("index.json has no system_graph")
        graph = C._read_json_file(C._safe_relpath(root, index["system_graph"], "index.system_graph"), "system graph")
        if not isinstance(graph, dict) or graph.get("schema") != C.GRAPH_SCHEMA or not isinstance(graph.get("objects"), list):
            raise C.ContainerError(f"system_graph.json is not a schema {C.GRAPH_SCHEMA} graph with objects")
        self.objects: dict[str, tuple[str, list[str]]] = {}
        for o in graph["objects"]:
            if not isinstance(o, dict) or not isinstance(o.get("id"), str) or o["id"] in self.objects:
                raise C.ContainerError("a graph object has no id, or a duplicate one")
            bindings = o.get("source_bindings") if isinstance(o.get("source_bindings"), list) else []
            prefixes = [b["tensor_prefix"] for b in bindings if isinstance(b, dict) and isinstance(b.get("tensor_prefix"), str)]
            self.objects[o["id"]] = (str(o.get("kind")), prefixes)
        reps = index.get("representations")
        if not isinstance(reps, dict) or not reps:
            raise C.ContainerError("index.json has no representations")
        self.reps, self.segments = reps, {}
        for rid, e in reps.items():
            if not isinstance(e, dict):
                raise C.ContainerError(f"representation {rid!r} is not an object")
            for k, ty in C._REP_REQUIRED.items():
                if not isinstance(e.get(k), ty) or (ty is int and not is_int(e.get(k))):
                    raise C.ContainerError(f"representation {rid!r}: field {k!r} missing or of the wrong type")
            if e["object"] not in self.objects or rid != f"{e['object']}@{e['encoding']}":
                raise C.ContainerError(f"representation {rid!r} does not name a graph object as <object>@<encoding>")
            if e["encoding"] not in (C.BF16, C.Q8_0):
                raise C.ContainerError(f"representation {rid!r}: unsupported encoding {e['encoding']!r}")
            if ("codec" in e or e["encoding"] == C.Q8_0) and (e.get("codec") != C.CODEC_Q8_0
                                                               or not C._codec_types_ok(e.get("codec"))):
                raise C.ContainerError(f"representation {rid!r}: codec is not exactly the Q8_0 identity")
            C._safe_relpath(root, e["segment"], f"representation {rid} segment")

    def seg(self, rid: str) -> C.Segment:
        """Parse and verify one representation's segment, on demand. §7 step 4: only the edited and re-derived
        segments are parsed, and their tables must be unambiguous (a duplicate tensor name is refused); a segment
        that is neither is judged as a whole file and never parsed."""
        if rid not in self.segments:
            e = self.reps[rid]
            seg = C._parse_segment(rid, C._safe_relpath(self.root, e["segment"], f"representation {rid} segment"), e, [])
            if e["encoding"] == C.BF16 and any(t.dtype != C.BF16 for t in seg.tensors):
                raise C.ContainerError(f"segment {rid}: a BF16 representation holds a non-BF16 tensor")
            C._verify_digests(seg, e)
            self.segments[rid] = seg
        return self.segments[rid]

    def read(self, rid: str, name: str) -> bytes:
        seg = self.seg(rid)
        e = seg.by_name[name]
        with open(seg.path, "rb") as f:
            f.seek(seg.payload_start + e.offset)
            data = f.read(e.len)
        if len(data) != e.len:
            raise C.ContainerError(f"short read of {rid}/{name}")
        return data


def tensor_bits(c: Store, rep_id: str, name: str) -> tuple[np.ndarray, bytes, tuple]:
    raw = c.read(rep_id, name)
    return np.frombuffer(raw, dtype="<u2").astype(np.uint16), raw, c.seg(rep_id).by_name[name].shape


