"""`WEIGHT_PATCHES_V4`: does a compiled container hold what its `weight-patches/v4` ledger declares of a base container?

Written from `docs/verification/weight-patches-v4.md` (§7 is the requirements list), with the numerics of
`conformance/vlp-numerics/v1` and `v2` implemented in `vlp_numerics.py`. The oracle is the BASE container plus the ops
the compiled container's ledger records, recomputed here. No hash, count or result the engine wrote is ever used as an
expected value: each is only CHECKED against what this verifier computes or reads from the containers itself.

Two verdicts, kept apart (§7 step 7):

* **numerical satisfaction** (§7 step 3, with step 6): every element of every tensor the ledger names equals the BF16
  bits recomputed from the base and the ops (or, for an element target, the base and the deltas). Outside the ops'
  footprint, and inside it where the v2 selection leaves an element untouched, that means the base's own bits.
* **ledger integrity and provenance** (§7 steps 1, 2, 4, 5): the ledger is bound to this base, every op is admissible
  (bounds, disjoint columns, a known schema, profile and op), every digest and count it records agrees with the
  containers and with the recomputation, every other tensor and file is unchanged, and the re-derived representations
  name the compiled canonical payload.

A container is verified only when both are `satisfied`. The report says which half failed.

**Not established, and said so in the answer:** the operands' `origin` (the op digest of §3a covers its text, not
where the operands came from) and the content of a re-derived (quantised) representation: its digests are chained to
the compiled canonical payload, but it is not re-quantised here.
"""

